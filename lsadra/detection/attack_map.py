"""
The one MITRE ATT&CK map LSADRA uses, pinned to a single Enterprise release.

Every technique ID the product shows (rules, narratives, parser hints, the
dashboard) must come through this module. ``data/attack-enterprise.json`` is a
compact copy of the pinned release's technique and tactic tables, generated by
``scripts/update_attack_data.py`` from MITRE's official STIX data.
``tests/test_attack_map.py`` fails CI when any rule, narrative or the demo corpus
names a technique that is unknown, revoked or deprecated in that release.

ATT&CK is (c) The MITRE Corporation, used under its Terms of Use.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Dict, List, Optional, Tuple

#: The ATT&CK Enterprise release every mapping is checked against.
ATTACK_VERSION = "20.1"

_DATA = Path(__file__).resolve().parent / "data" / "attack-enterprise.json"


@dataclass(frozen=True)
class Tactic:
    """An ATT&CK tactic, e.g. ``TA0006 Credential Access``."""

    id: str
    shortname: str
    name: str


@dataclass(frozen=True)
class Technique:
    """An ATT&CK technique or sub-technique with the tactics it serves."""

    id: str
    name: str
    tactics: Tuple[Tactic, ...]
    revoked: bool = False
    deprecated: bool = False
    revoked_by: Optional[str] = None

    @property
    def active(self) -> bool:
        """True when the technique is neither revoked nor deprecated."""
        return not (self.revoked or self.deprecated)

    @property
    def url(self) -> str:
        """The technique's page on attack.mitre.org."""
        return "https://attack.mitre.org/techniques/" + self.id.replace(".", "/") + "/"

    def as_dict(self) -> Dict[str, object]:
        """A JSON-friendly summary for APIs and the scorecard."""
        return {
            "id": self.id,
            "name": self.name,
            "tactics": [t.name for t in self.tactics],
            "tactic_ids": [t.id for t in self.tactics],
            "attack_version": ATTACK_VERSION,
        }


@lru_cache(maxsize=1)
def _table() -> Dict[str, object]:
    with _DATA.open(encoding="utf-8") as fh:
        table = json.load(fh)
    if table.get("attack_version") != ATTACK_VERSION:
        raise RuntimeError(
            f"{_DATA.name} holds ATT&CK {table.get('attack_version')}, "
            f"attack_map.py pins {ATTACK_VERSION}; rerun scripts/update_attack_data.py"
        )
    return table


@lru_cache(maxsize=1)
def tactics() -> Dict[str, Tactic]:
    """All active tactics, keyed by shortname (``credential-access``)."""
    raw = _table()["tactics"]
    return {short: Tactic(v["id"], short, v["name"]) for short, v in raw.items()}  # type: ignore[union-attr]


@lru_cache(maxsize=None)
def get_technique(technique_id: str) -> Optional[Technique]:
    """Look up a technique by ID, or ``None`` if the pinned release lacks it."""
    raw = _table()["techniques"].get(technique_id)  # type: ignore[union-attr]
    if raw is None:
        return None
    tac = tactics()
    return Technique(
        id=technique_id,
        name=raw["name"],
        tactics=tuple(tac[s] for s in raw.get("tactics", []) if s in tac),
        revoked=bool(raw.get("revoked")),
        deprecated=bool(raw.get("deprecated")),
        revoked_by=raw.get("revoked_by"),
    )


def technique(technique_id: str) -> Technique:
    """
    Return an active technique, or raise ``KeyError``.

    Rules call this at import time, so a stale or mistyped ID fails loudly
    instead of shipping a wrong label.
    """
    tech = get_technique(technique_id)
    if tech is None:
        raise KeyError(f"{technique_id} is not in ATT&CK Enterprise {ATTACK_VERSION}")
    if not tech.active:
        hint = f"; use {tech.revoked_by}" if tech.revoked_by else ""
        raise KeyError(f"{technique_id} is revoked or deprecated in ATT&CK {ATTACK_VERSION}{hint}")
    return tech


def is_valid(technique_id: str) -> bool:
    """True when the ID names an active technique in the pinned release."""
    tech = get_technique(technique_id)
    return tech is not None and tech.active


def technique_name(technique_id: str) -> str:
    """Display name for an ID, or the ID itself if unknown (never raises)."""
    tech = get_technique(technique_id)
    return tech.name if tech else technique_id


def tactic_names(technique_id: str) -> List[str]:
    """Tactic names for an ID, empty when unknown (never raises)."""
    tech = get_technique(technique_id)
    return [t.name for t in tech.tactics] if tech else []
